"""Validate the scorer on three cases with known answers, and write a report.

    uv run python scripts/39_validate_scorer.py <validation_cases.json> [out.md]

A scorer nobody has tested against a known answer is a guess with arithmetic on
top. The three cases are chosen so that each one can fail differently:

1. **The crystal, 7K4U.** Ground truth. The measurement code must reproduce the
   reference geometry exactly, and a *perturbation series on the real coordinates*
   must show the asymmetry the brief demands - too short punished harder than too
   long. The perturbation is what makes this more than a tautology.
2. **HG3.17 cofolded through the full pipeline**, with a real MSA. A measured
   170 000 M-1 s-1 Kemp eliminase. If the scorer does not rate a working enzyme
   above our own designs, it is not measuring catalysis.
3. **A collapsed design.** Must score at essentially zero. Checks that the
   multiplicative collapse actually fires.

Every expectation is stated before the number is shown, so the report cannot be
read as a post-hoc rationalisation.
"""

import json
import statistics
import sys
from pathlib import Path

from kemp.scoring import (
    CRYSTAL,
    WEIGHTS,
    approach_deviation,
    score_angle,
    score_burial,
    score_consistency,
    score_distance,
    score_ipde,
    weighted_total,
)

OUT_DEFAULT = Path("results/criteria/scorer_validation.md")


def sub_scores(geom, burial=None, ipde=None, consistency=None):
    sd = min(score_distance(geom[c]["d"], CRYSTAL[c]["dist"]) for c in ("base", "donor"))
    dev, what = approach_deviation(geom)
    parts = {
        "dist": sd,
        "approach": score_angle(dev),
        "ipde": None if ipde is None else score_ipde(ipde),
        "burial": None if burial is None else score_burial(burial),
        "consistency": consistency,
    }
    return parts, dev, what


def fmt(x, nd=3):
    return "n/a" if x is None else f"{x:.{nd}f}"


def main() -> int:
    data = json.loads(Path(sys.argv[1]).read_text(encoding="utf-8-sig"))
    out = Path(sys.argv[2]) if len(sys.argv) > 2 else OUT_DEFAULT
    L: list[str] = []
    checks: list[tuple[str, bool | None, str]] = []

    L += [
        "# Scorer validation: three cases with known answers",
        "",
        "Generated by `scripts/39_validate_scorer.py`. Every expectation is stated",
        "before its number. Weights: " + ", ".join(f"`{k}` {v}" for k, v in WEIGHTS.items()) + ".",
        "",
    ]

    # ---------------------------------------------------------------- Case 1
    L += [
        "## Case 1 - the crystal (7K4U motif)",
        "",
        "**Expectation:** the measurement code reproduces its own reference, so both",
        "geometry sub-scores must be 1.000. This only proves the measurement is",
        "self-consistent; the perturbation below is the real test.",
        "",
    ]
    g = data["crystal"]["geometry"]
    parts, dev, what = sub_scores(g)
    L += ["| contact | distance | angle | out of plane |", "|---|---|---|---|"]
    for c in ("base", "donor"):
        L.append(
            f"| {c} | {g[c]['d']:.3f} Å (target {CRYSTAL[c]['dist']}) | "
            f"{g[c]['angle']:.1f}° (target {CRYSTAL[c]['angle']}) | "
            f"{g[c]['oop']:.1f}° (target {CRYSTAL[c]['oop']}) |"
        )
    L += [
        "",
        f"`s_dist` = **{fmt(parts['dist'])}**, `s_approach` = "
        f"**{fmt(parts['approach'])}** (worst deviation {dev:.2f}°, {what or 'none'})",
        "",
    ]
    ok1 = parts["dist"] > 0.999 and parts["approach"] > 0.999
    checks.append(
        (
            "Case 1a: crystal reproduces its own reference",
            ok1,
            f"s_dist {fmt(parts['dist'])}, s_approach {fmt(parts['approach'])}",
        )
    )

    L += [
        "### Perturbation on the real coordinates",
        "",
        "**Expectation:** moving the base's OD2 along the OD2→N3 axis by the same",
        "amount must cost **more** when moving closer than when moving away.",
        "",
        "| shift | resulting distance | `s_dist` | side |",
        "|---|---|---|---|",
    ]
    # Zuordnung aus dem GEMESSENEN Abstand ableiten, nicht aus dem Vorzeichen der
    # Verschiebung: shift > 0 bewegt OD2 naeher an N3, verkuerzt also. Eine erste
    # Fassung dieses Tests hatte das verwechselt und meldete einen FAIL auf
    # korrektem Verhalten.
    target = CRYSTAL["base"]["dist"]
    rows = []
    for p in data["crystal_perturbed"]:
        sc = score_distance(p["d_base"], target)
        err = p["d_base"] - target
        rows.append({"shift": p["shift"], "d": p["d_base"], "err": err, "score": sc})
        # shift == 0 ist exakt die unverfaelschte Zeile. Der Zielwert 2.535 ist die
        # gerundete Fassung des gemessenen Abstands, daher bleibt dort ein Rest von
        # ~1e-4 A stehen - zu klein fuer den Score, aber zu gross fuer einen
        # Gleichheitstest auf err.
        side = "unperturbed (reference)" if p["shift"] == 0.0 else "shorter" if err < 0 else "longer"
        L.append(f"| {p['shift']:+.2f} Å | {p['d_base']:.3f} Å | {sc:.4f} | {side} |")
    asym = []
    for mag in (0.25, 0.5, 1.0):
        sh = min((r for r in rows if r["err"] < -1e-9), key=lambda r: abs(abs(r["err"]) - mag), default=None)
        lo = min((r for r in rows if r["err"] > 1e-9), key=lambda r: abs(abs(r["err"]) - mag), default=None)
        if sh and lo and abs(abs(sh["err"]) - abs(lo["err"])) < 0.02:
            asym.append((abs(sh["err"]), sh["score"], lo["score"]))
    ok2 = bool(asym) and all(short < long_ for _, short, long_ in asym)
    L += [""]
    for a, short, long_ in asym:
        L.append(
            f"- error of {a:.2f} Å: too short {short:.4f} vs too long {long_:.4f} → "
            f"penalty ratio **{long_ / short:.1f}×**"
        )
    checks.append(
        (
            "Case 1b: too short is punished harder than too long",
            ok2,
            "; ".join(f"{a:.2f} A: short {short:.3f} < long {long_:.3f}" for a, short, long_ in asym),
        )
    )

    # ---------------------------------------------------------------- Case 2
    L += [
        "",
        "## Case 2 - HG3.17, a real enzyme, through the full pipeline",
        "",
        "Measured activity 170 000 M⁻¹s⁻¹ (Broom et al.), cofolded with 6NT and a real",
        "MMseqs2 MSA, three Boltz-2 seeds.",
        "",
        "**Expectation:** a working enzyme must score **above our best design**",
        "(`zonghu_vA_s2`, 0.3090). If it does not, the scorer is not ranking catalysis.",
        "",
    ]
    runs = data.get("hg3_17") or []
    if not runs:
        L += [
            "> **Not available.** The cofold did not produce structures, so this case is",
            "> unresolved. The scorer is therefore **not** validated against a real enzyme.",
            "",
        ]
        checks.append(("Case 2: real enzyme outranks our best design", None, "cofold produced no structures"))
        hg_total = None
    else:
        L += ["| seed | base | donor | worst approach dev | iPDE | burial |", "|---|---|---|---|---|---|"]
        for i, r in enumerate(runs, 1):
            gg = r["geometry"]
            d2, w2 = approach_deviation(gg)
            L.append(
                f"| {i} | {gg['base']['d']:.2f} Å | {gg['donor']['d']:.2f} Å | "
                f"{d2:.0f}° ({w2}) | {fmt(r.get('ipde'), 2)} | {r.get('burial')} |"
            )
        bases = [r["geometry"]["base"]["d"] for r in runs]
        donors = [r["geometry"]["donor"]["d"] for r in runs]
        cons = (
            score_consistency([statistics.stdev(bases), statistics.stdev(donors)]) if len(runs) >= 2 else None
        )
        best = min(runs, key=lambda r: approach_deviation(r["geometry"])[0])
        gg = best["geometry"]
        p2, d2, w2 = sub_scores(gg, best.get("burial"), best.get("ipde"), cons)
        hg_total = weighted_total(p2)
        L += [
            "",
            f"Spread over seeds: base σ = {statistics.stdev(bases):.2f} Å, "
            f"donor σ = {statistics.stdev(donors):.2f} Å "
            f"(K5 = {fmt(cons)})"
            if len(runs) >= 2
            else "",
        ]
        L += ["", "| term | sub-score |", "|---|---|"]
        for k in WEIGHTS:
            L.append(f"| {k} | {fmt(p2.get(k))} |")
        L += ["", f"**Total = {hg_total:.4f}**", ""]
        ok3 = hg_total > 0.3090
        checks.append(
            ("Case 2: real enzyme outranks our best design (0.3090)", ok3, f"HG3.17 total {hg_total:.4f}")
        )

    # ---------------------------------------------------------------- Case 3
    L += ["## Case 3 - a collapsed design", ""]
    br = data.get("broken") or {}
    L += [
        f"`{br.get('name')}`, CA-RMSD from the RFD3 backbone {fmt(br.get('ca_rmsd'), 1)} Å.",
        "",
        "**Expectation:** total below 0.01 - the multiplicative collapse must fire.",
        "",
    ]
    gb = br.get("geometry")
    if gb:
        pb, db, wb = sub_scores(gb, br.get("burial"), br.get("ipde"))
        bt = weighted_total(pb)
        L += [
            f"base {gb['base']['d']:.2f} Å, donor {gb['donor']['d']:.2f} Å, "
            f"worst approach deviation {db:.0f}° ({wb})",
            "",
            "| term | sub-score |",
            "|---|---|",
        ]
        for k in WEIGHTS:
            L.append(f"| {k} | {fmt(pb.get(k))} |")
        L += ["", f"**Total = {bt:.6f}**", ""]
        ok4 = bt < 0.01
        checks.append(("Case 3: collapsed design scores ~0", ok4, f"total {bt:.6f}"))
    else:
        checks.append(("Case 3: collapsed design scores ~0", None, "geometry not measurable"))

    # ---------------------------------------------------------------- verdict
    L += ["## Verdict", "", "| check | result | evidence |", "|---|---|---|"]
    for name, ok, ev in checks:
        sym = {True: "PASS", False: "**FAIL**", None: "**unresolved**"}[ok]
        L.append(f"| {name} | {sym} | {ev} |")
    npass = sum(1 for _, o, _ in checks if o is True)
    nfail = sum(1 for _, o, _ in checks if o is False)
    nunk = sum(1 for _, o, _ in checks if o is None)
    L += ["", f"**{npass} passed, {nfail} failed, {nunk} unresolved.**", ""]
    if nunk or nfail:
        L += [
            "The scorer is **not** fully validated. An unresolved check is not a pass:",
            "it means the evidence to decide was never produced.",
            "",
        ]
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(L) + "\n", encoding="utf-8")
    print(f"written: {out}  ({npass} pass, {nfail} fail, {nunk} unresolved)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
